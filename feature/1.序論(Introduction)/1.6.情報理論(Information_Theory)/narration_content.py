SCENES = []

def scene(title, reference, rows):
    sid = f'scene{len(SCENES)+1:02}'
    beats = []
    for i, (visual, lines) in enumerate(rows, 1):
        segments = []
        for j, line in enumerate(lines, 1):
            display, speech = line if isinstance(line, tuple) else (line, line)
            ds = [x+'。' for x in display.split('。') if x]
            ss = [x+'。' for x in speech.split('。') if x]
            assert len(ds) == len(ss), (display, speech)
            for d, s in zip(ds, ss):
                segments.append(dict(id=f'{sid}-{i:02}-{len(segments)+1:02}', display=d, speech=s))
        beats.append(dict(seconds=8, visual_note=visual, segments=segments))
    SCENES.append(dict(id=sid, title=title, reference=reference, beats=beats))


SYNTHESIS_SETTINGS = {'speedScale': 1.08, 'intonationScale': 1.08,
                      'prePhonemeLength': .08, 'postPhonemeLength': .12, 'volumeScale': 1.0}

def estimated_duration(beat):
    return max(beat['seconds'], sum(len(s['speech']) for s in beat['segments']) / 6 + .8)

def script_hash(scene):
    return hashlib.sha256(json.dumps(dict(version=4, scene=scene, speaker=23,
        settings=SYNTHESIS_SETTINGS), ensure_ascii=False, sort_keys=True).encode()).hexdigest()


def estimated_duration(beat):
    return max(float(beat["seconds"]), sum(len(s["speech"]) for s in beat["segments"]) / 6.0 + 0.8)

SYNTHESIS_SETTINGS = {
    "speedScale": 1.08, "intonationScale": 0.95,
    "prePhonemeLength": 0.08, "postPhonemeLength": 0.12, "volumeScale": 1.0,
}

def script_hash(scene):
    payload = {"version": 4, "scene": scene, "speaker": 23, "settings": SYNTHESIS_SETTINGS}
    return hashlib.sha256(json.dumps(payload, ensure_ascii=False, sort_keys=True).encode()).hexdigest()


def write_script():
    from pathlib import Path
    lines = ['# PRML 1.4 次元の呪い — ナレーション台本', '',
             '字幕 display と音声 speech を分離。各段落のアニメーションは文音声の実測時間に同期する。',
             '原文: Bishop (2006), 印刷 pp.33–38。図は自作データ、1.4節に表はない。', '']
    for scene in SCENES:
        lines += [f"## {scene['id']} {scene['title']}", '', f"原文参照: {scene['reference']}", '']
        for i, beat in enumerate(scene['beats'], 1):
            lines += [f"### Beat {i}: {beat['visual_note']}", '']
            for s in beat['segments']:
                lines += [f"- `{s['id']}` 字幕: {s['display']}", f"  音声: {s['speech']}"]
            lines += ['']
    Path(__file__).with_name('narration_script.md').write_text('\n'.join(lines) + '\n')

if __name__ == '__main__':
    write_script()

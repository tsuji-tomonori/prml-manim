def beat(note, *pairs):
    return {"visual_note": note, "seconds": 6,
            "segments": [{"display": display, "speech": speech} for display, speech in pairs]}


def scene(index, title, reference, *beats):
    identifier = f"scene{index:02d}"
    for i, item in enumerate(beats, 1):
        for j, segment in enumerate(item["segments"], 1):
            segment["id"] = f"{identifier}-{i:02d}-{j:02d}"
    return {"id": identifier, "title": title, "reference": reference, "beats": list(beats)}



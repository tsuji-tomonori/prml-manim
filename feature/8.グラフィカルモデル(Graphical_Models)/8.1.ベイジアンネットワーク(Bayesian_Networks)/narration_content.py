SCENES=[]

def p(display, speech=None):
    if speech is None:
        if '$' in display: raise ValueError(display)
        speech=display
    for old,new in [('値','あたい'),('確率','かくりつ'),('分布','ぶんぷ'),('条件','じょうけん'),('事前','じぜん'),('事後','じご'),('観測','かんそく'),('予測','よそく'),('変数','へんすう'),('生成','せいせい'),('係数','けいすう'),('分散','ぶんさん'),('同時','どうじ'),('独立','どくりつ'),('積分','せきぶん'),('潜在','せんざい'),('総和','そうわ'),('正規','せいき'),('平均','へいきん'),('近似','きんじ'),('経路','けいろ'),('精度','せいど'),('重み','おもみ'),('標本','ひょうほん')]:
        speech=speech.replace(old,new)
    return display,speech


SCENES = []


def p(display, speech=None):
    if speech is None:
        if '$' in display:
            raise ValueError(display)
        speech = display
    for old, new in [('観測値', 'かんそくち'), ('数値', 'すうち'), ('値', 'あたい'),
                     ('推論', 'すいろん'), ('因子', 'いんし'), ('周辺', 'しゅうへん'),
                     ('確率', 'かくりつ'), ('分布', 'ぶんぷ'), ('観測', 'かんそく'),
                     ('積', 'せき'), ('和', 'わ'), ('最大', 'さいだい'),
                     ('状態', 'じょうたい'), ('局所', 'きょくしょ'),
                     ('式', 'しき'), ('表', 'ひょう'), ('重み', 'おもみ')]:
        speech = speech.replace(old, new)
    return display, speech


def scene(title, reference, beats):
    sid = f'scene{len(SCENES)+1:02d}'
    SCENES.append(dict(id=sid, title=title, reference=reference,
        beats=[dict(seconds=10, visual_note=note,
            segments=[dict(id=f'{sid}-{i:02d}-{j:02d}', display=d, speech=s)
                      for j, (d, s) in enumerate(lines, 1)])
                for i, (note, lines) in enumerate(beats, 1)]))



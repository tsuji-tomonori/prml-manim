from pathlib import Path

SCENES = []

def scene(title, reference, beats):
    sid = f'scene{len(SCENES)+1:02}'
    result = []
    for b, (note, sentences) in enumerate(beats, 1):
        segments = []
        for i, sentence in enumerate(sentences, 1):
            display, speech = (sentence, sentence) if isinstance(sentence, str) else sentence
            segments.append(dict(id=f'{sid}-{b:02}-{i:02}', display=display, speech=speech))
        result.append(dict(seconds=10, visual_note=note, segments=segments))
    SCENES.append(dict(id=sid, title=title, reference=reference, beats=result))


SYNTHESIS_SETTINGS = dict(speedScale=1.08, intonationScale=1.08, prePhonemeLength=.08, postPhonemeLength=.12, volumeScale=1.0)
def estimated_duration(beat):
    return max(beat['seconds'], sum(len(s['speech']) for s in beat['segments'])/6+.8)
def script_hash(scene):
    return hashlib.sha256(json.dumps(dict(version=4, scene=scene, speaker=23, settings=SYNTHESIS_SETTINGS), ensure_ascii=False, sort_keys=True).encode()).hexdigest()

def export_script():
    root = Path(__file__).resolve().parent
    manifest = root/'assets/voicevox/manifest.json'
    entries = {e['id']:e for e in json.loads(manifest.read_text()).get('scenes', [])} if manifest.exists() else {}
    lines = ['# PRML 2.4 指数型分布族：台本', '', '原文: Bishop (2006), §2.4、印刷pp.113–120（PDF pp.133–140）。この節に図・表はない。全図は式に基づく自作。', '', 'display は字幕、speech は収録文。尺は有効な新台本の音声がある場合のみ実測。', '']
    for s in SCENES:
        entry=entries.get(s['id'], {})
        durations=entry.get('beat_durations', []) if entry.get('script_sha256')==script_hash(s) else []
        lines += [f"## {s['id']} {s['title']}", '', f"原文: {s['reference']}。図・表なし。", '']
        for i,b in enumerate(s['beats']):
            duration=f'{durations[i]:.3f}秒' if durations else '未生成'
            lines += [f"### {i+1}. {b['visual_note']}（{duration}）", '']
            for seg in b['segments']:
                lines += [f"- {seg['id']} display: {seg['display']}", f"  speech: {seg['speech']}"]
            lines += ['']
    (root/'narration_script.md').write_text('\n'.join(lines)+'\n')
if __name__=='__main__':
    export_script()

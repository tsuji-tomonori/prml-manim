def script_hash(scene):
    return hashlib.sha256(json.dumps([scene,SYNTHESIS_SETTINGS],ensure_ascii=False,sort_keys=True).encode()).hexdigest()

def export():
    root=Path(__file__).resolve().parent
    p=root/'assets/voicevox/manifest.json'
    entries={s['id']:s for s in json.loads(p.read_text()).get('scenes',[])} if p.exists() else {}
    lines=['# PRML 2.2 多項変数：ナレーション台本','',
           '原文：Bishop (2006), §2.2、印刷pp.74–78（PDF pp.94–98）。式(2.25)–(2.41)、図2.4・2.5。表はありません。',
           '自作の三色の観測例を使用。シーン9の予測式は式(2.41)を積分した補足で、原文にない式番号は付けません。',
           '字幕はdisplay、合成はspeech。1 beatにつき一つの視覚操作を、文のPCM時間に合わせます。','']
    for s in SCENES:
        e=entries.get(s['id'],{})
        if e.get('script_sha256') != script_hash(s):
            e={}
        lines += [f"## {s['id']} {s['title']}", '',f"原文：{s['reference']}",f"音声尺：{e.get('duration','未生成')} 秒",'']
        for i,b in enumerate(s['beats']):
            lines += [f"### {i+1}. {b['visual_note']}",'']
            for v in b['segments']:
                lines += [f"- 字幕：{v['display']}",f"- 音声：{v['speech']}"]
            lines += ['']
    (root/'narration_script.md').write_text('\n'.join(lines)+'\n')

if __name__=='__main__':
    export()

SCENES = []

def scene(title, reference, beats):
    sid = f'scene{len(SCENES)+1:02}'
    result = dict(id=sid, title=title, reference=reference, beats=[])
    for i, (note, pairs) in enumerate(beats, 1):
        segments=[]
        for j, pair in enumerate(pairs, 1):
            display, speech = pair if isinstance(pair, tuple) else (pair, pair)
            segments.append(dict(id=f'{sid}-{i:02}-{j:02}', display=display, speech=speech))
        result['beats'].append(dict(visual_note=note, seconds=10, segments=segments))
    SCENES.append(result)


# Short connective lines keep each experiment tied to the same question.
def add_line(scene_index, beat_index, display, speech=None):
    beat = SCENES[scene_index]['beats'][beat_index]
    d, s = p(display, speech)
    beat['segments'].append(dict(id=f"scene{scene_index+1:02d}-{beat_index+1:02d}-{len(beat['segments'])+1:02d}",
                                 display=d, speech=s))


def p(display,speech=None):
    if speech is None:
        if '$' in display:
            raise ValueError(display)
        speech=display
    speech=(speech.replace('観測値','かんそくち').replace('予測値','よそくち')
            .replace('数値','すうち').replace('値','あたい').replace('点','てん')
            .replace('負担率','ふたんりつ').replace('尤度','ゆうど'))
    return display,speech


SCENES = []

def scene(title, reference, beats):
    i = len(SCENES) + 1
    rows = []
    for j, (note, pairs) in enumerate(beats, 1):
        segments = []
        for k, pair in enumerate(pairs, 1):
            display, speech = pair if isinstance(pair, tuple) else (pair, pair)
            segments.append(dict(id=f'scene{i:02}-{j:02}-{k:02}', display=display, speech=speech))
        rows.append(dict(seconds=10, visual_note=note, segments=segments))
    SCENES.append(dict(id=f'scene{i:02}', title=title, reference=reference, beats=rows))


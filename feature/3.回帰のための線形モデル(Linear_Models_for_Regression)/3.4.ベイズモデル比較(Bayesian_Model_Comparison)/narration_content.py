SCENES = []

def scene(title, reference, rows):
    sid = f'scene{len(SCENES)+1:02d}'
    beats=[]
    for i,(note, pairs) in enumerate(rows):
        segments=[]
        for j,pair in enumerate(pairs):
            display,speech = (pair,pair) if isinstance(pair,str) else pair
            segments.append(dict(id=f'{sid}-{i+1:02d}-{j+1:02d}',display=display,speech=speech))
        beats.append(dict(seconds=10,visual_note=note,segments=segments))
    SCENES.append(dict(id=sid,title=title,reference=reference,beats=beats))


SCENES = []


def p(display, speech=None):
    if speech is None:
        if '$' in display:
            raise ValueError(display)
        speech = display
    return display, (speech.replace("連続値", "連続ち")
                    .replace("値", "あたい").replace("期待あたい", "期待値")
                    .replace("黄色", "きいろ"))


def scene(title, reference, beats):
    sid = f'scene{len(SCENES)+1:02d}'
    SCENES.append(dict(id=sid,title=title,reference=reference,beats=[
        dict(seconds=9.0,visual_note=note,segments=[
            dict(id=f'{sid}-{i:02d}-{j:02d}',display=d,speech=s)
            for j,(d,s) in enumerate(lines,1)])
        for i,(note,lines) in enumerate(beats,1)]))



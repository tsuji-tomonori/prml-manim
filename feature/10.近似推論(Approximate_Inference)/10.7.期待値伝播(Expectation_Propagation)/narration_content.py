SCENES=[]

def p(display,speech=None):
    if speech is None:
        if '$' in display: raise ValueError(display)
        speech=display
    speech=(speech.replace('期待値伝播','きたいちでんぱ').replace('期待値','きたいち')
            .replace('負になる','ふになる').replace('負の','ふの').replace('値','あたい').replace('精度','せいど')
            .replace('近似','きんじ').replace('尤度','ゆうど').replace('分散','ぶんさん')
            .replace('下界','かかい').replace('事後','じご').replace('事前','じぜん').replace('因子','いんし')
            .replace('背景雑音','はいけいざつおん').replace('逆順','ぎゃくじゅん')
            .replace('同じ','おなじ'))
    return display,speech

def scene(title,reference,beats):
    sid=f'scene{len(SCENES)+1:02d}'
    SCENES.append(dict(id=sid,title=title,reference=reference,
        beats=[dict(seconds=10,visual_note=note,
                    segments=[dict(id=f'{sid}-{i:02d}-{j:02d}',display=d,speech=s)
                              for j,(d,s) in enumerate(lines,1)])
               for i,(note,lines) in enumerate(beats,1)]))


SCENES=[]

def p(display,speech=None):
    if speech is None:
        if '$' in display:
            raise ValueError(display)
        speech=display
    speech=(speech.replace('黄色','きいろ').replace('期待値','きたいち').replace('数値','すうち')
            .replace('値','あたい').replace('負の','ふの')
            .replace('下界','かかい').replace('上界','じょうかい')
            .replace('局所変分法','きょくしょへんぶんほう')
            .replace('凸双対','とつそうつい').replace('共役関数','きょうやくかんすう'))
    return display,speech


SCENES = []


def p(display, speech=None):
    if speech is None:
        if '$' in display:
            raise ValueError(display)
        speech = display
    speech = (speech.replace('期待十分統計量', 'きたいじゅうぶんとうけいりょう')
              .replace('期待値', 'きたいち').replace('観測値', 'かんそくち')
              .replace('値', 'あたい').replace('和', 'わ'))
    return display, speech


def scene(title, reference, beats):
    sid = f'scene{len(SCENES)+1:02d}'

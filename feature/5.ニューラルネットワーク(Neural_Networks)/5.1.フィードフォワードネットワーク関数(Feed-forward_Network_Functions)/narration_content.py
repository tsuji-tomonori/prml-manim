def line(display, speech=None):
    return dict(display=display, speech=display if speech is None else speech)


def scene(title, reference, rows):
    return dict(title=title, reference=reference, beats=[
        dict(seconds=10, visual_note=note, segments=segments) for note, segments in rows])



for i, item in enumerate(SCENES, 1):
    item['id'] = f'scene{i:02}'
    for j, beat in enumerate(item['beats'], 1):
        for k, segment in enumerate(beat['segments'], 1):
            segment['id'] = f'scene{i:02}-{j:02}-{k:02}'

# Only the spoken text is respelled; captions retain normal Japanese and mathematics.
for item in SCENES:
    for beat in item['beats']:
        for segment in beat['segments']:
            text = segment['speech']
            for before, after in [('正に固定', 'せいに固定'), ('した値', 'したあたい'),
                                  ('上の値', '上のあたい'), ('届いた値', '届いたあたい'),
                                  ('付きの値', '付きのあたい'), ('必要な値', '必要なあたい'),
                                  ('重みの値', '重みのあたい'), ('次の節', '次のせつ'),
                                  ('角の', 'かどの'), ('総和で割る', '総和でわる')]:
                text = text.replace(before, after)
            segment['speech'] = text

SYNTHESIS_SETTINGS = dict(speedScale=1.08, intonationScale=.95, prePhonemeLength=.08,
                          postPhonemeLength=.12, volumeScale=1.0)


def estimated_duration(beat):
    return max(beat['seconds'], sum(len(s['speech']) for s in beat['segments'])/6+.8)


def script_hash(scene):
    payload = dict(version=4, scene=scene, speaker=23, settings=SYNTHESIS_SETTINGS)
    return hashlib.sha256(json.dumps(payload, ensure_ascii=False, sort_keys=True).encode()).hexdigest()

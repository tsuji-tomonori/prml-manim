    story = SCENES[scene_index]
    story['beats'].insert(before, dict(seconds=12, visual_note=note,
        segments=[dict(id=f"{story['id']}-{kind}-{i+1:02d}", display=d, speech=s)
                  for i, (d, s) in enumerate(lines)]))


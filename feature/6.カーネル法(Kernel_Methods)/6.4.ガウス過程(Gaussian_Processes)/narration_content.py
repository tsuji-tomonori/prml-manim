SCENES = []


def p(display, speech=None):
    if speech is None:
        if '$' in display:
            raise ValueError(f'Provide a spoken reading: {display}')
        speech = display
    speech = (speech.replace('値', 'あたい').replace('重み', 'おもみ')
              .replace('共分散', 'きょうぶんさん').replace('分散', 'ぶんさん')
              .replace('条件付き', 'じょうけんつき').replace('事前', 'じぜん')
              .replace('事後', 'じご').replace('周辺尤度', 'しゅうへんゆうど')
              .replace('尤度', 'ゆうど').replace('正規化', 'せいきか')
              .replace('式', 'しき').replace('負の', 'マイナスの')
              .replace('半定あたい', 'はんていち').replace('真あたい', 'しんち')
              .replace('逆向きなら負、', '逆向きならマイナス、')
              .replace('黄色の', 'きいろの'))
    return display, speech


def scene(title, reference, beats):
    sid = f'scene{len(SCENES)+1:02d}'
    SCENES.append(dict(id=sid, title=title, reference=reference, beats=[
        dict(seconds=10, visual_note=note, segments=[
            dict(id=f'{sid}-{i:02d}-{j:02d}', display=d, speech=s)
            for j, (d, s) in enumerate(lines, 1)])
        for i, (note, lines) in enumerate(beats, 1)]))



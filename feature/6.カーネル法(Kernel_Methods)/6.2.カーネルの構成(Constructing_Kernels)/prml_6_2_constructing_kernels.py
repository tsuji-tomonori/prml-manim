def label(s,size=24,color=WHITE,pos=(0,0,0)):
    return jp(s,size,color).move_to(pos)
def formula(s,size=33,color=WHITE,pos=(0,-2.45,0)):
    m=tex(s,size,color).move_to(pos)
    if m.width>12.0:m.scale_to_fit_width(12.0)
    return m
def curve(ax,fn,xmin=-1.15,xmax=1.15,color=GREEN,width=3):
    xs=np.linspace(xmin,xmax,120)
    return VMobject().set_points_as_corners([ax.c2p(float(x),float(fn(x))) for x in xs]).set_stroke(color,width)

def comparison_table(values,center=(0,.1,0),cell=.9,fmt=None):
    border=VGroup();nums=VGroup();headers=VGroup()
    cx,cy,_=center
    for i in range(3):
        for j in range(3):
            at=(cx+(j-1)*cell,cy+(1-i)*cell,0)
            border.add(Square(side_length=cell,stroke_color=MUTED,stroke_width=1.2).move_to(at))
            v=float(values[i,j]);display=(fmt(v) if fmt else f'{v:.2f}'.rstrip('0').rstrip('.'))
            nums.add(formula(display,26,GREEN,at))
    for i,x in enumerate(X):
        headers.add(formula(f'{int(x)}',21,BLUE,(cx-2*cell,cy+(1-i)*cell,0)))
        headers.add(formula(f'{int(x)}',21,PURPLE,(cx+(i-1)*cell,cy+2*cell,0)))
    return border,nums,headers


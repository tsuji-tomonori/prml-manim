SCENES = []

def scene(title, reference, beats):
    sid = f"scene{len(SCENES)+1:02d}"
    rows = []
    for i, (note, lines) in enumerate(beats, 1):
        rows.append(dict(seconds=10, visual_note=note, segments=[
            dict(id=f"{sid}-{i:02d}-{j:02d}", display=d, speech=s)
            for j, (d, s) in enumerate(lines, 1)]))
    SCENES.append(dict(id=sid, title=title, reference=reference, beats=rows))

def p(display, speech=None):
    """Keep visible notation while disambiguating common VOICEVOX readings."""
    reading = speech if speech is not None else display
    reading = reading.replace('同じ点', 'おなじ点')
    reading = reading.replace('負', 'マイナス').replace('行', 'ぎょう')
    reading = reading.replace('目標値', '目標ち').replace('予測値', '予測ち')
    reading = reading.replace('値', 'あたい')
    return display, reading



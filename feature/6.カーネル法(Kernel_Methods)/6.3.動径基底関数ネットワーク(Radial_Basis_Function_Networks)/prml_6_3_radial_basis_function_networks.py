def FadeIn(mobject,**kwargs):
    # Keep the referred object visible during the first spoken sentence.
    kwargs.setdefault('rate_func',lambda t:smooth(min(1.,5*t)))
    return _MANIM_FADE_IN(mobject,**kwargs)
def L(s,x=0,y=0,size=24,color=WHITE):
    return jp(s,size,color).move_to((x,y,0))
def F(s,x=0,y=0,size=34,color=WHITE):
    m=tex(s,size,color).move_to((x,y,0))
    if m.width>11.8:m.scale_to_fit_width(11.8)
    return m
def curve(ax,fn,a=-1.4,b=3.,color=GREEN,width=3):
    xs=np.linspace(a,b,141)
    return VMobject().set_points_smoothly([ax.c2p(float(x),float(fn(x))) for x in xs]).set_stroke(color,width)
def plot(with_probe=True):
    ax=Axes(x_range=[-1.5,3.,.5],y_range=[-.15,1.55,.25],x_length=9.2,y_length=4.25,tips=False,axis_config=dict(color=MUTED,stroke_width=1.3,include_ticks=False)).move_to((0,-.1,0))
    ticks=VGroup()
    for x in [-1,0,1,2.5]:
        ticks.add(Line(ax.c2p(x,-.15),ax.c2p(x,-.12),color=MUTED,stroke_width=1))
        ticks.add(F(str(x),ax.c2p(x,-.15)[0],ax.c2p(x,-.15)[1]-.27,19,MUTED))
    ticks.add(F('x',ax.c2p(3,-.15)[0]+.18,ax.c2p(3,-.15)[1],22,WHITE))
    dots=VGroup(*[Dot(ax.c2p(x,t),radius=.072,color=BLUE) for x,t in zip(X,T)])
    guide=DashedLine(ax.c2p(PROBE,-.08),ax.c2p(PROBE,1.25),color=YELLOW,dash_length=.08,stroke_width=2)
    if with_probe:return ax,ticks,dots,guide
    return ax,ticks,dots

def three_bars(values,heading='各点の寄与',colors=COLORS,scale=2.3,baseline=-1.3):
    group=VGroup(L(heading,0,2.15,25,YELLOW))
    for i,(v,c) in enumerate(zip(values,colors)):
        x=(i-1)*3.1
        h=max(.025,float(v)*scale)
        group.add(Line((x,baseline,0),(x,baseline+h,0),stroke_width=19,color=c))
        group.add(F(f'{float(v):.4f}',x,baseline+h+.28,24,c))
        group.add(F(f'x_{i+1}',x,baseline-.43,24,c))
    return group

class PRML63RadialBasisFunctionNetworks(NarratedScene):
    def construct(self):
        self.camera.background_color=BG
        self.manifest={e['id']:e for e in json.loads(MANIFEST.read_text())['scenes']}
        self.timeline=[]
        methods=[self.opening,self.bases,self.interpolation,self.normalize,self.vote,self.probability,self.fewer,self.return_to_question]
        for i,method in enumerate(methods):
            self.begin(i);method()
            assert self.beat_index==len(SCENES[i]['beats']),(i,self.beat_index)
            self.timeline[-1]['end']=float(self.time)
        Path(config.media_dir,'prml63_timeline.json').write_text(json.dumps(self.timeline,ensure_ascii=False,indent=2)+'\n')


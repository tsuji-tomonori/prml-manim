SCENES=[]

def p(display,speech=None):
    if speech is None:
        if '$' in display: raise ValueError(display)
        speech=display
    for old,new in [('値','あたい'),('重み','おもみ'),('係数','けいすう'),('精度','せいど'),('事前','じぜん'),('事後','じご'),('尤度','ゆうど'),('周辺','しゅうへん'),('予測','よそく'),('分散','ぶんさん'),('曲線','きょくせん'),('基底','きてい'),('証拠','しょうこ'),('負の','マイナスの'),('幅','はば'),('確率','かくりつ'),('積分','せきぶん'),('黄色','きいろ')]:
        speech=speech.replace(old,new)
    speech=speech.replace('はばが','広がりが').replace('からはばも','から広がりも')
    return display,speech


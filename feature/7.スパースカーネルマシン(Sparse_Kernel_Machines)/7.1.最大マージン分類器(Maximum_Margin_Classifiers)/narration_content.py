SCENES=[]


def p(display, speech=None):
    if speech is None:
        if '$' in display:
            raise ValueError(display)
        speech=display
    speech=(speech.replace('値','あたい').replace('重み','おもみ')
            .replace('境界','きょうかい').replace('余白','よはく')
            .replace('係数','けいすう').replace('双対','そうつい')
            .replace('制約','せいやく').replace('正準','せいじゅん')
            .replace('負の','マイナスの').replace('正の','プラスの')
            .replace('正、','プラス、').replace('負と','マイナスと')
            .replace('黄色','きいろ').replace('章の名前','しょうの名前'))
    return display,speech



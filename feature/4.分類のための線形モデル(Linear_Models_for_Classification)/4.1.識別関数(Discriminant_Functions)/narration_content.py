MATH_READINGS = {r'w':'ダブリュー',r'w_0':'ダブリューゼロ',r'r':'アール',r'J(w)':'ジェイ、ダブリュー',r'N/N_1':'エヌ割るエヌいち',r'-N/N_2':'マイナス、エヌ割るエヌに',r'K':'ケー',r'K-1':'ケーマイナスいち',r'\phi(x)':'ファイ、エックス'}

def speech_for(text):
    for math,reading in MATH_READINGS.items():
        text=text.replace('$'+math+'$',reading)
    text=text.replace('Fisher','フィッシャー')
    for a,b in [('黄色','きいろ'),('負','ふ'),('超える値','超えるあたい'),('両方が正','両方がせい'),('重なり','かさなり'),('誤分類','ごぶんるい'),('四つの角','四つのすみ'),('どちら側','どちらがわ'),('次の節','次のせつ')]:
        text=text.replace(a,b)
    return text


import hashlib,json
SCENES=[]
def p(display,speech=None):
    if speech is None:
        if '$' in display:raise ValueError(display)
        speech=display
    for a,b in [('確率','かくりつ'),('分布','ぶんぷ'),('値','あたい'),('標本','ひょうほん'),('採用','さいよう'),('連鎖','れんさ'),('条件付き','じょうけんつき'),('不変','ふへん'),('相関','そうかん'),('過緩和','かかんわ'),('分散','ぶんさん'),('平均','へいきん'),('更新','こうしん'),('密度','みつど'),('収束','しゅうそく'),('周辺','しゅうへん'),('逆向き','ぎゃくむき')]:speech=speech.replace(a,b)
    return display,speech


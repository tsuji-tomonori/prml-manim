    SCENES.append(dict(id=sid,title=title,reference=ref,beats=[dict(seconds=9.5,visual_note=note,segments=[dict(id=f'{sid}-{i:02d}-{j:02d}',display=d,speech=s) for j,(d,s) in enumerate(lines,1)]) for i,(note,lines) in enumerate(beats,1)]))


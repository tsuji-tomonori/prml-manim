SCENES=[]
def p(display,speech=None):
    if speech is None:
        if '$' in display: raise ValueError(display)
        speech=display
    for a,b in [('値','あたい'),('確率','かくりつ'),('密度','みつど'),('分布','ぶんぷ'),('標本','ひょうほん'),('一様','いちよう'),('棄却','きゃっか'),('条件付き','じょうけんつき'),('周辺','しゅうへん'),('採用','さいよう'),('変数','へんすう')]:
        speech=speech.replace(a,b)
    return display,speech


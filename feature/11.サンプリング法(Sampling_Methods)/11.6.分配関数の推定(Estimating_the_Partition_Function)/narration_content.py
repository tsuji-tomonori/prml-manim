SCENES=[]
def p(display,speech=None):
    if speech is None:
        if '$' in display: raise ValueError(display)
        speech=display
    for a,b in [('重なり','かさなり'),('推定値','すいていち'),('値','あたい'),('分配関数','ぶんぱいかんすう'),('確率','かくりつ'),('密度','みつど'),('分布','ぶんぷ'),('標本','ひょうほん'),('期待値','きたいち'),('重要度','じゅうようど'),('正規化','せいきか'),('連鎖法','れんさほう'),('重み','おもみ')]:
        speech=speech.replace(a,b)
    return display,speech


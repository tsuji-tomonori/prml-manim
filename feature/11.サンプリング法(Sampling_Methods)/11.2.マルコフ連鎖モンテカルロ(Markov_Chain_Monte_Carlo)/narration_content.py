import hashlib,json
SCENES=[]
def p(display,speech=None):
    if speech is None:
        if '$' in display:raise ValueError(display)
        speech=display
    for a,b in [('閾値','しきいち'),('数値','すうち'),('期待値','きたいち'),('値','あたい'),('確率','かくりつ'),('分布','ぶんぷ'),('標本','ひょうほん'),('棄却','ききゃく'),('採択','さいたく'),('連鎖','れんさ'),('詳細','しょうさい'),('提案','ていあん'),('近似','きんじ'),('自己相関','じこそうかん'),('不変','ふへん')]:speech=speech.replace(a,b)
    return display,speech


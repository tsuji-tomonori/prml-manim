import hashlib,json
SCENES=[]
def p(display,speech=None):
    if speech is None:
        if '$' in display:raise ValueError(display)
        speech=display
    speech=(speech.replace('期待値','きたいち').replace('数値','すうち').replace('閾値','しきいち').replace('値','あたい').replace('確率','かくりつ').replace('重点','じゅうてん')
            .replace('棄却','ききゃく').replace('累積','るいせき').replace('分布','ぶんぷ')
            .replace('期待','きたい').replace('正規','せいき').replace('標本','ひょうほん')
            .replace('再標本化','さいひょうほんか').replace('近似','きんじ')
            .replace('密度','みつど').replace('指数','しすう').replace('一様','いちよう')
            .replace('同じ','おなじ').replace('右端','みぎはし').replace('SIR法','エスアイアール法').replace('対数凹','たいすうおう'))
    return display,speech


SCENES=[]
def p(display,speech=None):
    if speech is None:
        if '$' in display: raise ValueError(display)
        speech=display
    for a,b in [('確率','かくりつ'),('密度','みつど'),('分布','ぶんぷ'),('標本','ひょうほん'),('一様','いちよう'),('棄却','きゃっか'),('条件付き','じょうけんつき'),('採用','さいよう'),('変数','へんすう'),('勾配','こうばい'),('位相空間','いそうくうかん'),('運動量','うんどうりょう'),('詳細釣り合い','しょうさいつりあい'),('負の','ふの')]:
        speech=speech.replace(a,b)
    return display,speech

